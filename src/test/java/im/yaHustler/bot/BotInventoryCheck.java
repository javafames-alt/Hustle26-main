package im.yaHustler.bot;

import java.util.ArrayList;
import java.util.List;
import im.yaHustler.bot.world.BotInventory;
import im.yaHustler.bot.world.BotPlayerState;
import net.minecraft.network.chat.Component;
import net.minecraft.network.protocol.game.*;
import net.minecraft.world.inventory.MenuType;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;
import static org.junit.jupiter.api.Assertions.*;

final class BotInventoryCheck {
    static void run() {
        var lookup = net.minecraft.data.registries.VanillaRegistries.createWorldLookup();
        net.minecraft.core.registries.BuiltInRegistries.DATA_COMPONENT_INITIALIZERS.build(lookup).forEach(net.minecraft.core.component.DataComponentInitializers.PendingComponents::apply);
        var first = new BotInventory();
        var second = new BotInventory();
        var slots = new ArrayList<ItemStack>();
        for (int i = 0; i < 46; i++) slots.add(ItemStack.EMPTY);
        var sword = new ItemStack(Items.DIAMOND_SWORD);
        slots.set(38, sword);
        slots.set(45, new ItemStack(Items.SHIELD));
        first.handle(new ClientboundContainerSetContentPacket(0, 17, slots, ItemStack.EMPTY));
        first.handle(new ClientboundSetHeldSlotPacket(2));
        assertTrue(first.mainHand().is(Items.DIAMOND_SWORD));
        assertTrue(first.offHand().is(Items.SHIELD));
        assertEquals(17, first.snapshot().stateId());
        assertTrue(second.mainHand().isEmpty());
        sword.setCount(0);
        first.mainHand().setCount(0);
        first.playerSlots().get(38).setCount(0);
        assertEquals(1, first.mainHand().getCount());
        first.handle(new ClientboundSetPlayerInventoryPacket(36, new ItemStack(Items.DIAMOND_BOOTS)));
        first.handle(new ClientboundSetPlayerInventoryPacket(39, new ItemStack(Items.DIAMOND_HELMET)));
        assertTrue(first.playerSlots().get(8).is(Items.DIAMOND_BOOTS));
        assertTrue(first.playerSlots().get(5).is(Items.DIAMOND_HELMET));
        first.handle(new ClientboundOpenScreenPacket(3, MenuType.GENERIC_9x1, Component.literal("Bot chest")));
        var chestSlots = new ArrayList<ItemStack>();
        for (int i = 0; i < 45; i++) chestSlots.add(ItemStack.EMPTY);
        chestSlots.set(0, new ItemStack(Items.APPLE, 4));
        chestSlots.set(38, new ItemStack(Items.DIAMOND_SWORD));
        first.handle(new ClientboundContainerSetContentPacket(3, 20, chestSlots, new ItemStack(Items.STICK)));
        first.handle(new ClientboundContainerSetSlotPacket(3, 20, 9, new ItemStack(Items.COBBLESTONE, 32)));
        assertEquals(32, first.playerSlots().get(9).getCount());
        first.handle(new ClientboundSetPlayerInventoryPacket(10, new ItemStack(Items.DIRT, 8)));
        assertTrue(first.snapshot().slots().get(10).is(Items.DIRT));
        first.handle(new ClientboundContainerSetDataPacket(3, 2, 100));
        first.handle(new ClientboundContainerSetSlotPacket(3, 21, 0, new ItemStack(Items.APPLE, 5)));
        assertEquals(5, first.snapshot().slots().getFirst().getCount());
        assertEquals(100, first.snapshot().properties().get(2));
        assertEquals(21, first.snapshot().stateId());
        first.snapshot().slots().getFirst().setCount(0);
        first.handle(new ClientboundContainerSetSlotPacket(2, 99, 0, ItemStack.EMPTY));
        first.handle(new ClientboundContainerClosePacket(2));
        first.handle(new ClientboundContainerSetContentPacket(2, 99, List.of(), ItemStack.EMPTY));
        assertEquals(3, first.snapshot().id());
        assertEquals(5, first.snapshot().slots().getFirst().getCount());
        assertTrue(first.cursor().is(Items.STICK));
        first.handle(new ClientboundContainerSetContentPacket(0, 18, slots, new ItemStack(Items.APPLE)));
        assertTrue(first.cursor().is(Items.STICK));
        first.handle(new ClientboundSetPlayerInventoryPacket(2, new ItemStack(Items.DIAMOND_SWORD)));
        first.handle(new ClientboundContainerClosePacket(3));
        assertEquals(0, first.snapshot().id());
        assertEquals(18, first.snapshot().stateId());
        assertTrue(first.cursor().is(Items.APPLE));
        assertTrue(first.mainHand().is(Items.DIAMOND_SWORD));
        assertTrue(first.snapshot().properties().isEmpty());
        first.handle(new ClientboundSetHeldSlotPacket(99));
        assertEquals(2, first.selectedSlot());
        first.reset();
        assertTrue(first.mainHand().isEmpty());
        assertTrue(first.cursor().isEmpty());
        var player = new BotPlayerState();
        var other = new BotPlayerState();
        player.apply(new ClientboundSetExperiencePacket(0.5f, 100, 7));
        player.apply(new ClientboundSetHealthPacket(6, 12, 2));
        assertEquals(6, player.vitals().health());
        assertEquals(7, player.vitals().experienceLevel());
        assertEquals(100, player.vitals().totalExperience());
        assertEquals(20, other.vitals().health());
        System.out.println("Bot inventory slot mapping, container lifecycle, item copies and player state isolation checks passed.");
    }
}
